import streamlit as st

# הגדרות עמוד (עיצוב שונה מעט - פריסה רחבה ושימוש ב-Tabs/Expanders)
st.set_page_config(page_title="פרויקט 1: ניתוח מחירי בתים", page_icon="🏠", layout="wide")

st.title("🏠 פרויקט 1: הכרות עם הדאטה")
st.subheader("ניתוח חקרני ומסקנות לקראת מודל רגרסיה | מאגר מחירי בתים (House Prices)")
st.divider()

# --- 1. על הדאטה ---
st.markdown("### 📌 1. על הדאטה שנבחר")
st.write("""
* **מקור הנתונים:** מאגר נתוני נדל"ן (House Price Prediction Dataset) הכולל 2,000 תצפיות.
* **מה מייצגת כל שורה?** כל שורה בטבלה מייצגת **בית יחיד** שהוצע למכירה, ומכילה פרטים פיזיים ותחזוקתיים כמו שטח הבית, מספר חדרים, שנת בנייה ומחיר.
* **למה נבחר הדאטה הזה?** מדובר בדאטה אינטואיטיבי, עם קשרים לוגיים ברורים (למשל, בית גדול = מחיר גבוה), המאפשר לבנות מודל רגרסיה בעל ערך עסקי ומעשי להערכת שווי נכסים.
""")

# --- 2. מידע על הנתונים והממוצעים ---
st.markdown("### 📊 2. מידע על הנתונים והממוצעים")

col1, col2, col3, col4 = st.columns(4)
col1.metric("מספר שורות", "2,000")
col2.metric("מספר עמודות", "10")
col3.metric("מחיר ממוצע", "$537,676")
col4.metric("שטח ממוצע", "2,786 מ\"ר/רגל")

st.markdown("""
**ערכים חסרים בדאטה:**
* **אין ערכים חסרים כלל.** כל 10 העמודות מכילות 2,000 ערכים תקינים (0 Nulls).
* **הסבר ומשמעות:** המאגר נקי ומוכן לעבודה. אין צורך לבצע מחיקת שורות או השלמת נתונים (Imputation) שעלולים לעוות את הסטטיסטיקה של הנתונים המקוריים.

**הסבר על הממוצעים המרכזיים:**
* **מחיר ממוצע (Price - $537,676):** 
  נתון הגיוני המשקף מחיר של בית משפחתי טיפוסי באזורי פרברים או ערים בינוניות (תלוי אזור בארה"ב/בעולם).
* **מספר חדרי שינה ממוצע (Bedrooms - 3 חדרים):** 
  מייצג מבנה סטנדרטי ונפוץ מאוד של בית למשפחה ממוצעת, מה שמעיד על כך שהמדגם לא מוטה לטובת אחוזות ענק או דירות סטודיו.
""")

st.divider()

# --- 3. הגדרת המודל ---
st.markdown("### 🎯 3. הגדרת מודל החיזוי המתוכנן")

st.info("""
**עמודת החיזוי (y): `Price` (מחיר הבית)**  
* **נימוק לבחירה:** מדובר בעמודה מספרית רציפה המתאימה למודל רגרסיה. ניבוי הערך הכספי של הנכס הוא המטרה העסקית המרכזית של קונים, מוכרים ושמאי נדל"ן.
""")

st.markdown("**עמודות לחיזוי (Features) ונימוקים ללא Data Leakage:**")

c1, c2 = st.columns(2)
with c1:
    st.markdown("""
    📐 **Area (שטח הבית)**
    * **נימוק:** הגורם המשמעותי ביותר המשפיע על מחיר הבית. ככל שיש יותר שטח, הנכס מציע יותר מרחב ולכן ערכו עולה.
    * **בדיקת זליגה (Leakage):** שטח הבית הוא עובדה פיזית מוגמרת שידועה הרבה לפני שהנכס מוצע למכירה או שמחירו נקבע. המידע זמין מראש ואינו מושפע מהמחיר.
    """)
with c2:
    st.markdown("""
    🛠️ **Condition (מצב הבית)**
    * **נימוק:** בית במצב מצוין חוסך לקונה הוצאות שיפוץ עתידיות, ולכן הקונים מוכנים לשלם עליו "פרמיה" לעומת בית במצב ירוד.
    * **בדיקת זליגה (Leakage):** מצב הנכס (Poor, Fair, Good, Excellent) מוערך על ידי שמאי או מתווך לפני היציאה לשוק, ולכן ניתן להשתמש בו לחיזוי המחיר ללא חשש לזליגה.
    """)

st.divider()

# --- 4. מסקנות מרכזיות מניתוח הנתונים ---
st.markdown("### 💡 4. מסקנות מרכזיות מניתוח הנתונים (מבוסס על הגרפים)")

# עיצוב שונה מחבר שלך: שימוש ב-Tabs עבור המסקנות לקבלת מראה נקי יותר
tab1, tab2, tab3 = st.tabs(["מסקנה 1: התפלגות המצב", "מסקנה 2: חדרי שינה מול מחיר", "מסקנה 3: מצב הבית מול מחיר"])

text_tab1 = (
    "#### 📊 התפלגות מצב הבתים\n"
    "**מסקנה למודל:** הנתונים מציגים פיזור מאוזן היטב בין קטגוריות המצב"
    " השונות, מה שמבטיח שלמודל יהיה ייצוג מספק מכל סוג בית למניעת הטיות"
    " (Bias) ומאפשר למידה אמינה של כלל הקבוצות בסט הנתונים."
)

text_tab2 = (
    "#### 🛏️ השפעת מספר חדרי השינה על המחיר\n"
    "**מסקנה למודל:** מכיוון שמספר החדרים לבדו אינו מייצר שונות ניכרת במחיר"
    " הממוצע, המודל יצטרך להישען על שילוב מאפיינים נוספים (כמו שטח הבית) כדי"
    " ללמוד ולחזות את תמחור הבתים בצורה מדויקת."
)

text_tab3 = (
    "#### 🛠️ השפעת מצב הבית על המחיר\n"
    "**מסקנה למודל:** מצב הבית כמשתנה יחיד אינו מייצר הפרדה חדה במחיר"
    " הממוצע, ולכן יש לשלב אותו במודל יחד עם מאפיינים נוספים כדי לאפשר לו"
    " ללמוד את מורכבות התמחור בצורה מיטבית."
)

with tab1:
  st.markdown(text_tab1)

with tab2:
  st.markdown(text_tab2)

with tab3:
  st.markdown(text_tab3)
