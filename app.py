import streamlit as st

# הגדרת עיצוב העמוד
st.set_page_config(page_title="פרויקט חיזוי מחירי בתים", page_icon="🏠", layout="centered")

# כותרת ראשית
st.title("פרויקט חיזוי מחירי בתים 🏠")
st.markdown("גיא לוסטמן")
st.divider()

# --- חלק 1: מידע על הנתונים ---
st.header("📊 מידע על הנתונים")

col1, col2 = st.columns(2)
with col1:
    st.metric(label="מספר בתים (שורות)", value="2,000")
with col2:
    st.metric(label="מספר מאפיינים (עמודות)", value="10")

st.markdown("""
**חלוקת העמודות בדאטה:**
* **7 עמודות מספריות:** `Id` (מזהה הבית), `Area` (שטח הבית), `Bedrooms` (מספר חדרי שינה), `Bathrooms` (מספר חדרי רחצה), `Floors` (מספר קומות), `YearBuilt` (שנת בנייה) ו־`Price` (מחיר הבית).
* **3 עמודות קטגוריאליות (טקסט):** `Location` (מיקום), `Condition` (מצב הבית) ו־`Garage` (מידע על המוסך).
""")

st.success("**ערכים חסרים:** בבדיקת הנתונים לא נמצאו ערכים חסרים באף אחת מהעמודות. כל 10 העמודות מכילות 2,000 ערכים תקינים, ולכן אין עמודות בעייתיות ואין צורך בניקוי נתונים.")

st.divider()

# --- חלק 2: משתני המודל ---
st.header("🎯 משתני המודל והנימוקים")

st.info("**עמודת החיזוי (y): `Price`**\n\nהעמודה שנבחרה לחיזוי מייצגת את מחיר הבית. המטרה היא לבנות מודל רגרסיה שיוכל לחזות את מחירו של בית על סמך המאפיינים השונים שלו.")

st.markdown("#### העמודות שנבחרו לחיזוי (X):")
st.markdown("""
1. **שטח הבית (`Area`)**: ככל ששטח הבית גדול יותר, סביר שמחירו יהיה גבוה יותר.
2. **מצב הבית (`Condition`)**: מצב הבית משפיע ישירות על המחיר, שכן בתים במצב טוב יקרים יותר מבתים הזקוקים לשיפוץ.
""")

st.divider()

# --- חלק 3: פירוט הגרפים והמסקנות ---
st.header("📈 פירוט הגרפים והמסקנות")

st.subheader("1. גרף ספירה: כמות הבתים לפי מצב הבית (`countplot`)")
st.markdown("""
* **הסבר:** הגרף מציג את התפלגות השכיחויות – כמה בתים יש בנתונים מכל דרגת מצב (`Condition`).
* **למה בחרתי אותו:** כדי להבין את מבנה קובץ הנתונים (Data Distribution) ולראות האם רוב הבתים במצב טוב, סביר או מוזנח.
""")

st.subheader("2. גרף עמודות: מחיר ממוצע לפי מספר חדרי שינה (`barplot`)")
st.markdown("""
* **הסבר:** הגרף מציג את המחיר הממוצע של בתים בהתאם למספר חדרי השינה שקיימים בהם.
* **למה בחרתי אותו:** כדי להבין את הקשר בין גודל הבית (מבוטא במספר חדרים) לבין המחיר שלו, ולזהות אם תוספת חדרים מעלה את המחיר באופן רציף.
""")

st.subheader("3. גרף עמודות: מחיר ממוצע לפי מצב הבית (`barplot`)")
st.markdown("""
* **הסבר:** הגרף מציג את המחיר הממוצע של בתים עבור כל דרגת מצב תחזוקתי/פיזי (`Condition`).
* **למה בחרתי אותו:** כדי לבדוק כיצד מצב התחזוקה והאיכות של הבית משפיעים ישירות על השווי שלו בשוק.
""")
